    private bool _isEnglish;
    public static LanguageService Instance { get; } = new();
    internal bool IsEnglish
    {
        get => _isEnglish;
        set
        {
            if (_isEnglish == value) return;
            _isEnglish = value;
            OnPropertyChanged();
            OnPropertyChanged("Item[]");
        }
    }
    public string this[string key] => (IsEnglish ? English : Chinese).TryGetValue(key, out var value) ? value : key;
    public event PropertyChangedEventHandler? PropertyChanged;
    private void OnPropertyChanged([CallerMemberName] string? property = null) => PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(property));
}
